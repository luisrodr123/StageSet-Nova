const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("stageSetDesktop", {
  showInfo:()=>ipcRenderer.invoke('show:info'),showCreate:(name,previous)=>ipcRenderer.invoke('show:create',name,previous),showOpen:()=>ipcRenderer.invoke('show:open'),showSave:snapshot=>ipcRenderer.invoke('show:save',snapshot),showZip:()=>ipcRenderer.invoke('show:zip'),showDetach:()=>ipcRenderer.invoke('show:detach'),
  hostStart: config=>ipcRenderer.invoke('host:start',config),
  hostStop: ()=>ipcRenderer.invoke('host:stop'),
  hostClients: ()=>ipcRenderer.invoke('host:clients'),
  hostAssign: (id,output)=>ipcRenderer.invoke('host:assign',id,output),
  hostPublish: (id,frame)=>ipcRenderer.invoke('host:publish',id,frame),
  hostValidate: id=>ipcRenderer.invoke('host:validate',id),
  onHostRequest: callback=>{const listener=async(_,request)=>{let response;try{response={result:await callback(request)};}catch(error){response={error:error.message};}await ipcRenderer.invoke('host:response',{id:request.id,...response});};ipcRenderer.on('host:request',listener);return ()=>ipcRenderer.removeListener('host:request',listener);},
  hostCertificate: ()=>ipcRenderer.invoke('host:certificate'),
  hostAuthInfo:()=>ipcRenderer.invoke('host:authInfo'),hostAuthPassword:value=>ipcRenderer.invoke('host:authPassword',value),hostAuthForget:()=>ipcRenderer.invoke('host:authForget'),
  dmxStart: config=>ipcRenderer.invoke('dmx:start',config),
  dmxStop: ()=>ipcRenderer.invoke('dmx:stop'),
  dmxCue: event=>ipcRenderer.invoke('dmx:cue',event),
  dmxBlackout: ()=>ipcRenderer.invoke('dmx:blackout'),
  convertEps: data => ipcRenderer.invoke('background:eps',data),
  sessionInfo: () => ipcRenderer.invoke('session:info'),
  startSession: config => ipcRenderer.invoke('session:start',config),
  stopSession: () => ipcRenderer.invoke('session:stop'),
  chooseSlave: (id,selected) => ipcRenderer.invoke('session:choose',id,selected),
  handoffMaster: id => ipcRenderer.invoke('session:handoff',id),
  publishSessionState: value => ipcRenderer.invoke('session:state',value),
  sessionFeedback: message => ipcRenderer.invoke('session:feedback',message),
  onSessionEvent: callback => {const listeners=['status','control','lost','failure','role'].map(name=>{const fn=(_,data)=>callback(name,data);ipcRenderer.on(`session:${name}`,fn);return [name,fn];});return ()=>listeners.forEach(([name,fn])=>ipcRenderer.removeListener(`session:${name}`,fn));},
  startIpMidi: config => ipcRenderer.invoke('ipmidi:start',config),
  stopIpMidi: () => ipcRenderer.invoke('ipmidi:stop'),
  sendIpMidi: (id,data,delay) => ipcRenderer.invoke('ipmidi:send',id,data,delay),
  clearIpMidi: id => ipcRenderer.invoke('ipmidi:clear',id),
  onIpMidiMessage: callback => { const listener=(_,data)=>callback(data);ipcRenderer.on('ipmidi:message',listener);return ()=>ipcRenderer.removeListener('ipmidi:message',listener); },
  onIpMidiStatus: callback => { const listener=(_,data)=>callback(data);ipcRenderer.on('ipmidi:status',listener);return ()=>ipcRenderer.removeListener('ipmidi:status',listener); },
  selectStemDeck: () => ipcRenderer.invoke("stemdeck:select"),
  launchStemDeck: () => ipcRenderer.invoke("stemdeck:launch"),
  listDisplays: () => ipcRenderer.invoke("displays:list"),
  assignDisplay: (target, id) => ipcRenderer.invoke("displays:assign", target, id),
});
